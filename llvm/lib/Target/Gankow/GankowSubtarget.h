// The Gankow subtarget. It owns the per-function codegen objects
// (frame lowering, instruction info, register info, and the SelectionDAG
// lowering) and exposes them through the TargetSubtargetInfo virtual hooks.
//
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_GANKOW_GANKOWSUBTARGET_H
#define LLVM_LIB_TARGET_GANKOW_GANKOWSUBTARGET_H

#include "MCTargetDesc/GankowMCTargetDesc.h"
#include "GankowFrameLowering.h"
#include "GankowInstrInfo.h"
#include "GankowISelLowering.h"

// Pull in the generated GankowGenSubtargetInfo base-class declaration.
#define GET_SUBTARGETINFO_HEADER
#include "GankowGenSubtargetInfo.inc"

namespace llvm {

class GankowSubtarget : public GankowGenSubtargetInfo {
public:
  GankowSubtarget(const Triple &TT, StringRef CPU, StringRef FS,
                  const TargetMachine &TM);
  // Parses features string setting specified subtarget options. The
  // definition of this function is auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const GankowRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const GankowInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const GankowTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const GankowFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  // Feature accessors (generated from GankowFeatures.td).
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER) \
  bool GETTER() const { return ATTRIBUTE; }
#include "GankowGenSubtargetInfo.inc"

private:
  // Feature bits (generated from GankowFeatures.td).
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER) \
  bool ATTRIBUTE = DEFAULT;
#include "GankowGenSubtargetInfo.inc"

  GankowFrameLowering FrameLowering;
  GankowInstrInfo InstrInfo;
  GankowTargetLowering TLInfo;

  /// Initializes using the passed in CPU and feature strings so that we can
  /// use initializer lists for subtarget initialization.
  GankowSubtarget &initializeSubtargetDependencies(const Triple &TT,
                                                  StringRef CPU,
                                                  StringRef TuneCPU,
                                                  StringRef FS,
                                                  StringRef ABIName);
  
  unsigned getNumRegs() const{
    if(HasR8) 
      return 8;
    if(HasR16) 
      return 16;
    if(HasR32) 
      return 32;
    if(HasR64) 
      return 64;
    return 128;
  }
};

} // namespace llvm

#endif
